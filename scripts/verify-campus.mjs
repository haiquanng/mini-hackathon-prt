import { chromium, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'

const base = process.env.PROTOTYPE_URL || 'http://localhost:4173'
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const report = { checks: [], accessibility: [], errors: [], screenshots: [] }
await mkdir('artifacts', { recursive: true })
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
  const page = await context.newPage()
  page.on('pageerror', error => report.errors.push(error.message))
  async function open(path) {
    const response = await page.goto(`${base}${path}`, { waitUntil: 'networkidle' })
    assert.equal(response.status(), 200, `Direct URL ${path}`)
    assert.equal(new URL(page.url()).hash, '')
  }
  async function shot(name) {
    await page.screenshot({ path: `artifacts/${name}.png` })
    report.screenshots.push(`${name}.png`)
  }
  await page.goto(`${base}/#/di-den?to=i109`, { waitUntil: 'networkidle' })
  assert.equal(new URL(page.url()).pathname, '/di-den')
  assert.equal(new URL(page.url()).hash, '')
  await page.reload({ waitUntil: 'networkidle' })
  assert.equal(await page.getByLabel('Điểm đến', { exact: true }).inputValue(), 'i109')
  await page.locator('.bottom-nav').getByRole('link', { name: 'Đã lưu' }).click()
  await page.goBack()
  await page.getByRole('heading', { name: 'Mình đi từ đâu?' }).waitFor()
  await page.goForward()
  await page.getByRole('heading', { name: 'Những nơi muốn quay lại' }).waitFor()
  report.checks.push('Legacy hash redirects; direct reload and browser back/forward preserve clean routes')

  await open('/')
  await page.evaluate(() => localStorage.setItem('vinuni-ar-map.mock-photo-pins.v1', JSON.stringify([{ photoId: 'campus', point: { x: 0, z: 6 }, placeId: 'lobby' }])))
  await page.reload({ waitUntil: 'networkidle' })
  await page.locator('.scene-canvas canvas').waitFor()
  assert.equal(await page.locator('.map-pin, .photo-map-pin, .filter-chip').count(), 0)
  const select = page.getByRole('combobox', { name: 'Lọc loại địa điểm' })
  const filterBox = await select.boundingBox(), searchBox = await page.locator('.search-toolbar .search-box').boundingBox()
  assert.ok(filterBox.x >= searchBox.x + searchBox.width && Math.abs(filterBox.y - searchBox.y) <= 2)
  await select.selectOption('relax')
  assert.equal(await page.locator('.map-result').count(), 2)
  await page.getByRole('searchbox', { name: 'Tìm phòng hoặc địa điểm' }).fill('ca phe')
  assert.equal(await page.locator('.map-result').count(), 1)
  await page.reload({ waitUntil: 'networkidle' })
  assert.equal(await select.inputValue(), 'relax')
  assert.equal(await page.locator('.map-result').count(), 1)
  await page.locator('.map-result').getByRole('button', { name: /Quầy cà phê Toà I/ }).click()
  await page.locator('.destination-card').getByRole('heading', { name: 'Quầy cà phê' }).waitFor()
  assert.equal(await select.inputValue(), 'all')
  await page.getByRole('link', { name: 'Thử ảnh mẫu' }).click()
  assert.equal(new URL(page.url()).searchParams.get('to'), 'coffee')
  report.checks.push('No place/photo pins or filter chips, including with old saved pins; right-side dropdown filters with search and preserves URL; photo flow keeps chosen destination')

  await open('/anh-mau?to=i109')
  assert.equal(await page.locator('.sample-card').count(), 3)
  await page.getByRole('link', { name: /Kiến trúc khuôn viên.*Thử ảnh này/ }).click()
  await page.getByRole('heading', { name: 'Đang tìm vị trí…' }).waitFor()
  await page.getByRole('heading', { name: 'Đây có phải nơi bạn đang đứng?' }).waitFor()
  assert.equal(new URL(page.url()).pathname, '/xac-nhan-vi-tri')
  await expect(page.getByRole('radio', { name: /Sảnh Toà I/ })).toBeChecked()
  await page.getByText('Kết quả mô phỏng, chưa có nhận diện AI thật.').waitFor()
  await shot('flow-match-mobile')
  await page.getByRole('button', { name: 'Đúng, mình đang ở đây' }).click()
  assert.equal(await page.getByLabel('Điểm xuất phát', { exact: true }).inputValue(), 'lobby')
  assert.equal(await page.getByLabel('Điểm đến', { exact: true }).inputValue(), 'i109')
  await page.getByRole('button', { name: 'Xem hành trình' }).click()
  await page.getByRole('heading', { name: 'Đi thẳng', exact: true }).waitFor()
  report.checks.push('Sample photo → visible locating → disclosed mock result → explicit confirmation → route with correct origin and destination')

  await open('/anh-mau?to=coffee')
  await page.getByRole('link', { name: /Không gian học tập.*Thử ảnh này/ }).click()
  await page.getByRole('heading', { name: 'Bạn đang ở vị trí nào?' }).waitFor()
  assert.equal(await page.getByRole('radio').count(), 3)
  await expect(page.getByRole('button', { name: 'Đúng, mình đang ở đây' })).toBeDisabled()
  const study = page.getByRole('radio', { name: /Khu tự học mở/ })
  await study.focus()
  await page.keyboard.press('Space')
  await expect(study).toBeChecked()
  await page.getByRole('button', { name: 'Đúng, mình đang ở đây' }).click()
  assert.equal(await page.getByLabel('Điểm xuất phát', { exact: true }).inputValue(), 'study')
  assert.equal(await page.getByLabel('Điểm đến', { exact: true }).inputValue(), 'coffee')
  report.checks.push('Ambiguous sample requires explicit choice; keyboard radio selection starts route from selected candidate')

  await open('/anh-mau?to=i109')
  await page.getByRole('link', { name: /VinUni từ trên cao.*Thử ảnh này/ }).click()
  await page.getByRole('heading', { name: 'Chưa xác định được vị trí' }).waitFor()
  assert.equal(await page.getByRole('radio').count(), 0)
  assert.equal(await page.getByRole('button', { name: 'Đúng, mình đang ở đây' }).count(), 0)
  await page.getByRole('link', { name: 'Thử ảnh khác' }).click()
  assert.equal(new URL(page.url()).searchParams.get('to'), 'i109')
  await page.getByRole('link', { name: /VinUni từ trên cao.*Thử ảnh này/ }).click()
  await page.getByRole('heading', { name: 'Chưa xác định được vị trí' }).waitFor()
  await page.getByRole('link', { name: 'Chọn điểm xuất phát', exact: true }).click()
  await page.getByRole('link', { name: 'Sảnh Toà I', exact: true }).click()
  assert.equal(await page.getByLabel('Điểm xuất phát', { exact: true }).inputValue(), 'lobby')
  assert.equal(await page.getByLabel('Điểm đến', { exact: true }).inputValue(), 'i109')
  report.checks.push('Unrecognized photo offers retry or manual origin without inventing a result; destination preserved')

  await open('/anh-mau?to=i109')
  await page.getByRole('link', { name: /Kiến trúc khuôn viên.*Thử ảnh này/ }).click()
  await page.getByRole('link', { name: 'Đổi ảnh', exact: true }).click()
  await page.waitForTimeout(1500)
  assert.equal(new URL(page.url()).pathname, '/anh-mau')
  await open('/ghim-anh?mau=campus&to=coffee')
  await page.getByRole('heading', { name: 'Thử định vị từ một tấm ảnh' }).waitFor()
  assert.equal(new URL(page.url()).pathname, '/anh-mau')
  assert.equal(new URL(page.url()).searchParams.get('to'), 'coffee')
  report.checks.push('Cancel stops pending recognition navigation; retired pin URL redirects to photo flow with destination')

  for (const route of ['/', '/anh-mau', '/xac-nhan-vi-tri?mau=campus', '/xac-nhan-vi-tri?mau=classroom', '/xac-nhan-vi-tri?mau=aerial', '/xac-nhan-vi-tri?mau=unknown']) {
    await open(route)
    const audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    report.accessibility.push({ route, violations: audit.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) })) })
    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: width > 800 ? 900 : 844 })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.body.scrollWidth <= innerWidth), `Overflow: ${route}, ${width}`)
      assert.equal(await page.locator('.bottom-nav a').count(), 3)
    }
    await page.setViewportSize({ width: 390, height: 844 })
  }
  report.checks.push('All photo outcomes, invalid-photo fallback and exploration checked for accessibility and overflow at 320/390/768/1440 px')

  await open('/anh-mau?to=i109')
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload({ waitUntil: 'networkidle' })
  assert.ok(await page.evaluate(() => Boolean(navigator.serviceWorker.controller)))
  await context.setOffline(true)
  await page.reload({ waitUntil: 'networkidle' })
  assert.equal(await page.locator('.sample-card img').evaluateAll(imgs => imgs.filter(img => img.complete && img.naturalWidth > 0).length), 3)
  await page.getByRole('link', { name: /Kiến trúc khuôn viên.*Thử ảnh này/ }).click()
  await page.getByRole('heading', { name: 'Đây có phải nơi bạn đang đứng?' }).waitFor()
  await page.reload({ waitUntil: 'networkidle' })
  await page.getByRole('button', { name: 'Đúng, mình đang ở đây' }).click()
  await page.getByRole('button', { name: 'Xem hành trình' }).click()
  await page.getByRole('heading', { name: 'Đi thẳng', exact: true }).waitFor()
  await context.setOffline(false)
  report.checks.push('Offline gallery images, locating flow, result direct reload and route all work')

  for (const [path, width, name] of [['/', 390, 'flow-home-mobile'], ['/', 1440, 'flow-home-desktop'], ['/anh-mau', 390, 'flow-gallery-mobile'], ['/xac-nhan-vi-tri?mau=classroom', 390, 'flow-choices-mobile'], ['/xac-nhan-vi-tri?mau=aerial', 390, 'flow-unknown-mobile'], ['/xac-nhan-vi-tri?mau=classroom', 1440, 'flow-choices-desktop']]) {
    await page.setViewportSize({ width, height: width > 800 ? 900 : 844 })
    await open(path)
    if (path === '/') await page.locator('.scene-canvas canvas').waitFor()
    await shot(name)
  }
  assert.deepEqual(report.errors, [])
  assert.equal(report.accessibility.flatMap(a => a.violations).length, 0, 'Accessibility findings: see photo-flow-verification.json')
} finally {
  await writeFile('artifacts/photo-flow-verification.json', JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
  await browser.close()
}
