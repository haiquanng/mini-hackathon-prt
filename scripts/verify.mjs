import { chromium } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'

const base = process.env.PROTOTYPE_URL || 'http://localhost:4173'
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const report = { base, checks: [], accessibility: [], errors: [], screenshots: [] }
await mkdir('artifacts', { recursive: true })
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, reducedMotion: 'reduce' })
  const page = await context.newPage()
  page.on('pageerror', error => report.errors.push(error.message))
  async function screenshot(name) {
    await page.screenshot({ path: `artifacts/${name}.png`, fullPage: false })
    report.screenshots.push(`${name}.png`)
  }
  await page.goto(base, { waitUntil: 'networkidle' })
  await page.evaluate(() => document.fonts.ready)
  await page.getByRole('heading', { name: 'Khám phá VinUni' }).waitFor()
  for (const width of [320, 390, 768, 1280, 1440, 1920]) {
    await page.setViewportSize({ width, height: width > 800 ? 900 : 844 })
    const measured = await page.evaluate(() => ({ body: document.body.scrollWidth, root: document.documentElement.scrollWidth, width: innerWidth }))
    assert.ok(measured.body <= measured.width && measured.root <= measured.width, `Horizontal overflow: ${JSON.stringify(measured)}`)
    if ([320, 390].includes(width)) await screenshot(`explore-${width}`)
  }
  report.checks.push('No horizontal overflow at 320, 390, 768, 1280, 1440, 1920 pixels')
  await page.setViewportSize({ width: 390, height: 844 })
  let audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  report.accessibility.push({ screen: 'explore', violations: audit.violations.map(v => ({ id: v.id, impact: v.impact, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) })) })

  const search = page.getByRole('searchbox', { name: 'Tìm phòng hoặc địa điểm' })
  await search.fill('ca phe')
  assert.equal(await page.locator('.place-row').count(), 1)
  await page.locator('.explorer-results').getByText('Quầy cà phê', { exact: true }).waitFor()
  await search.fill('C501')
  await page.getByRole('heading', { name: 'Chưa thấy nơi bạn tìm' }).waitFor()
  await screenshot('search-empty-390')
  await page.getByRole('button', { name: 'Xem các địa điểm' }).click()
  await page.locator('.destination-card').getByRole('button', { name: 'Lưu Phòng I109', exact: true }).click()
  await page.locator('.bottom-nav').getByRole('link', { name: /Đã lưu/ }).click()
  await page.getByRole('heading', { name: 'Những nơi muốn quay lại' }).waitFor()
  await page.locator('.place-row').getByText('Phòng I109', { exact: true }).waitFor()
  await page.reload({ waitUntil: 'networkidle' })
  assert.equal(await page.locator('.place-row').count(), 1)
  await screenshot('saved-390')
  report.checks.push('Accent-insensitive search, empty state, saved places persist across reload')

  await page.goto(`${base}/di-den?to=i109`)
  await page.getByLabel('Điểm xuất phát', { exact: true }).selectOption('lobby')
  await screenshot('plan-390')
  await page.getByRole('button', { name: 'Xem hành trình' }).click()
  await page.getByRole('heading', { name: 'Đi thẳng', exact: true }).waitFor()
  await screenshot('journey-390')
  await page.getByRole('button', { name: 'Đã tới Khởi nghiệp' }).click()
  await page.reload({ waitUntil: 'networkidle' })
  await page.getByRole('heading', { name: 'Rẽ phải', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Chặng trước' }).click()
  await page.getByRole('heading', { name: 'Đi thẳng', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Đã tới Khởi nghiệp' }).click()
  await page.getByRole('button', { name: 'Đã tới Tự học' }).click()
  await page.getByRole('button', { name: 'Đã tới I109' }).click()
  await page.getByRole('heading', { name: 'Tới nơi rồi!' }).waitFor()
  await screenshot('arrived-390')
  report.checks.push('Three-step route, previous step, reload restores progress, arrival')

  await page.goto(`${base}/anh?to=i109`)
  await page.getByLabel('Chọn ảnh vị trí', { exact: true }).setInputFiles('public/images/classroom.webp')
  await page.getByText('Ảnh đã chọn, chưa nhận diện vị trí').waitFor()
  await page.waitForFunction(() => document.querySelector('.camera-preview img')?.naturalWidth === 240)
  await page.getByLabel('Chọn ảnh vị trí', { exact: true }).setInputFiles({ name: 'invalid.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') })
  await page.getByRole('alert').filter({ hasText: 'Hãy chọn ảnh JPG' }).waitFor()
  await screenshot('photo-390')
  report.checks.push('Local photo preview makes no AI match claim; invalid image type rejected')

  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'geolocation', { configurable: true, value: { getCurrentPosition: (_success, failure) => failure({ code: 1 }) } })
  })
  await page.goto(`${base}/vi-tri?to=i109`)
  await page.getByRole('button', { name: /Dùng vị trí điện thoại/ }).click()
  await page.getByText('Bạn chưa cấp quyền vị trí.', { exact: false }).waitFor()
  await page.getByRole('link', { name: 'Sảnh Toà I', exact: true }).click()
  assert.equal(await page.getByLabel('Điểm xuất phát', { exact: true }).inputValue(), 'lobby')
  report.checks.push('Location permission denial falls back to manual origin selection')
  audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  report.accessibility.push({ screen: 'plan', violations: audit.violations.map(v => ({ id: v.id, impact: v.impact, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) })) })

  await page.getByRole('button', { name: 'Cài VinUni AR Map', exact: true }).click()
  await page.getByRole('dialog').waitFor()
  await screenshot('install-390')
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('dialog').count(), 0)
  const manifest = await page.evaluate(async () => (await fetch('/manifest.webmanifest')).json())
  assert.equal(manifest.display, 'standalone')
  assert.equal(manifest.lang, 'vi')
  for (const icon of manifest.icons) {
    const response = await page.request.get(`${base}${icon.src}`)
    assert.equal(response.status(), 200)
  }
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.goto(base, { waitUntil: 'networkidle' })
  await page.reload({ waitUntil: 'networkidle' })
  assert.ok(await page.evaluate(() => Boolean(navigator.serviceWorker.controller)))
  await context.setOffline(true)
  await page.reload({ waitUntil: 'networkidle' })
  await page.getByRole('heading', { name: 'Khám phá VinUni' }).waitFor()
  assert.equal(await page.evaluate(async () => (await fetch('/pets/boba/spritesheet.webp')).status), 200)
  await page.locator('.scene-canvas canvas').waitFor()
  await search.fill('I109')
  await page.locator('.place-row').getByText('Phòng I109', { exact: true }).waitFor()
  await screenshot('offline-390')
  await page.goto(`${base}/di-den?from=lobby&to=i109`)
  await page.getByRole('button', { name: 'Xem hành trình' }).click()
  await page.getByRole('heading', { name: 'Đi thẳng', exact: true }).waitFor()
  report.checks.push('Manifest and install icons valid; registered service worker serves reload, Boba sprite, 3D chunk, search and route while offline')
  assert.deepEqual(report.errors, [])
  await context.close()
  await writeFile('artifacts/verification.json', JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
} finally { await browser.close() }
